function toAvva(t) { return Array.from(t).map(c => MAP[c] || c).join(""); }
function applyCop(root) {
  root.querySelectorAll(".cop").forEach(el => {
    el.classList.add("avva");
    el.textContent = toAvva(el.textContent);
  });
}